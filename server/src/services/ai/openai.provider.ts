import { IAIProvider, AIGenerateOptions } from './aiProvider.interface.js';
import { env } from '../../config/env.js';
import { ApiError } from '../../utils/apiError.js';
import { logger } from '../../utils/logger.js';

export class OpenAIProvider implements IAIProvider {
  private apiKey: string;
  private model: string;
  private timeoutMs: number;
  private defaultMaxTokens: number;

  constructor(
    apiKey?: string,
    model?: string,
    timeoutMs?: number,
    defaultMaxTokens?: number
  ) {
    this.apiKey = apiKey || env.AI_API_KEY;
    this.model = model || env.AI_MODEL || 'gpt-4o-mini';
    this.timeoutMs = timeoutMs || env.AI_TIMEOUT_MS || 30000;
    this.defaultMaxTokens = defaultMaxTokens || env.AI_MAX_TOKENS || 2048;
  }

  getProviderName(): string {
    return 'openai';
  }

  isConfigured(): boolean {
    return Boolean(this.apiKey && this.apiKey.trim().length > 0);
  }

  private ensureConfigured(): void {
    if (!this.isConfigured()) {
      throw ApiError.serviceUnavailable(
        'AI provider "openai" is not configured. Please configure AI_API_KEY in the server environment.'
      );
    }
  }

  async generateText(prompt: string, options?: AIGenerateOptions): Promise<string> {
    this.ensureConfigured();

    const timeout = options?.timeoutMs || this.timeoutMs;
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeout);

    const messages: Array<{ role: string; content: string }> = [];
    if (options?.systemPrompt) {
      messages.push({ role: 'system', content: options.systemPrompt });
    }
    messages.push({ role: 'user', content: prompt });

    try {
      const response = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${this.apiKey}`,
        },
        body: JSON.stringify({
          model: this.model,
          messages,
          temperature: options?.temperature ?? 0.7,
          max_tokens: options?.maxTokens ?? this.defaultMaxTokens,
        }),
        signal: controller.signal,
      });

      clearTimeout(timer);

      if (!response.ok) {
        const errorText = await response.text();
        logger.error(`[OpenAIProvider] API error (${response.status}): ${errorText}`);

        if (response.status === 429) {
          throw ApiError.tooManyRequests(
            'AI rate limit reached with OpenAI API. Please try again shortly.'
          );
        }

        if (response.status === 401 || response.status === 403) {
          throw ApiError.internal(
            'AI provider authentication failed. Please verify the server AI_API_KEY configuration.'
          );
        }

        throw ApiError.badGateway(
          `AI provider returned an error (${response.status}). Please try again later.`
        );
      }

      const data = (await response.json()) as any;
      const content = data?.choices?.[0]?.message?.content;

      if (!content) {
        throw ApiError.badGateway('AI provider returned an empty response.');
      }

      return content.trim();
    } catch (err: any) {
      clearTimeout(timer);
      if (err.name === 'AbortError') {
        throw ApiError.gatewayTimeout(
          `AI request timed out after ${timeout}ms. Please try a shorter prompt or try again later.`
        );
      }
      if (err instanceof ApiError) {
        throw err;
      }
      logger.error('[OpenAIProvider] Network failure:', err);
      throw ApiError.badGateway(`Failed to communicate with AI provider: ${err.message}`);
    }
  }

  async generateStructured<T>(
    prompt: string,
    schemaDescription: string,
    options?: AIGenerateOptions
  ): Promise<T> {
    const structuredPrompt = `${prompt}

IMPORTANT: You MUST respond ONLY with a valid JSON object or array conforming to this exact specification:
${schemaDescription}
Do NOT include markdown code blocks, do NOT add introductory or concluding text. Return only the raw JSON.`;

    const rawOutput = await this.generateText(structuredPrompt, {
      ...options,
      temperature: options?.temperature ?? 0.2,
    });

    let sanitized = rawOutput.trim();
    if (sanitized.startsWith('```json')) {
      sanitized = sanitized.slice(7);
    } else if (sanitized.startsWith('```')) {
      sanitized = sanitized.slice(3);
    }
    if (sanitized.endsWith('```')) {
      sanitized = sanitized.slice(0, -3);
    }
    sanitized = sanitized.trim();

    try {
      return JSON.parse(sanitized) as T;
    } catch (parseErr: any) {
      logger.error('[OpenAIProvider] Malformed JSON generated by model:', {
        rawOutput,
        error: parseErr.message,
      });
      throw ApiError.badGateway(
        'AI provider generated malformed structured content. Please retry the request.'
      );
    }
  }
}
