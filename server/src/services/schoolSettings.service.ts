  /**
   * Update Academic Calendar & Policy Settings
   */
  public static async updateAcademic(
    schoolId: Types.ObjectId | string,
    input: UpdateAcademicSettingsInput,
    actorId?: string,
    ip?: string,
    ua?: string
  ): Promise<ISchoolSettingsDoc> {
    const sId = new Types.ObjectId(schoolId);
    const settings = await this.getOrCreateSettings(sId);

    if (input.activeSessionId) {
      const session = await AcademicSession.findOne({
        _id: new Types.ObjectId(input.activeSessionId),
        schoolId: sId,
        isDeleted: false,
      });

      if (!session) {
        throw ApiError.badRequest('Referenced academic session not found in this school.');
      }

      // Atomically set isCurrent: true on referenced session and isCurrent: false on others
      await AcademicSession.updateMany(
        { schoolId: sId, _id: { $ne: session._id } },
        { $set: { isCurrent: false, status: 'completed' } }
      );
      session.isCurrent = true;
      session.status = 'active';
      await session.save();

      settings.academic.activeSessionId = session._id as any;
      await School.findByIdAndUpdate(sId, { $set: { 'settings.academicYear': session.name } });
    }

    if (input.workingDays) settings.academic.workingDays = input.workingDays;
    if (input.termsCount) settings.academic.termsCount = input.termsCount;

    settings.updatedBy = actorId ? new Types.ObjectId(actorId) : undefined;
    await settings.save();

    await this.logAudit(sId, 'UPDATE_SCHOOL_ACADEMIC', 'SchoolSettings', actorId, input, ip, ua);
    return settings;
  }

  /**
   * Add Academic Holiday to Calendar
   */
  public static async addHoliday(
    schoolId: Types.ObjectId | string,
    input: HolidayInput,
    actorId?: string
  ): Promise<ISchoolSettingsDoc> {
    const sId = new Types.ObjectId(schoolId);
    const settings = await this.getOrCreateSettings(sId);

    const holiday: any = {
      _id: new Types.ObjectId(),
      name: input.name,
      startDate: new Date(input.startDate),
      endDate: new Date(input.endDate),
      type: input.type,
      description: input.description,
    };

    settings.academic.holidays.push(holiday);
    settings.updatedBy = actorId ? new Types.ObjectId(actorId) : undefined;
    await settings.save();

    await this.logAudit(sId, 'ADD_ACADEMIC_HOLIDAY', 'SchoolSettings', actorId, holiday);
    return settings;
  }

  /**
   * Update Academic Holiday
   */
  public static async updateHoliday(
    schoolId: Types.ObjectId | string,
    holidayId: string,
    input: HolidayInput,
    actorId?: string
  ): Promise<ISchoolSettingsDoc> {
    const sId = new Types.ObjectId(schoolId);
    const settings = await this.getOrCreateSettings(sId);

    const holiday = settings.academic.holidays.find((h: any) => h._id.toString() === holidayId);
    if (!holiday) {
      throw ApiError.notFound('Holiday not found.');
    }

    holiday.name = input.name;
    holiday.startDate = new Date(input.startDate);
    holiday.endDate = new Date(input.endDate);
    if (input.type) holiday.type = input.type;
    if (input.description !== undefined) holiday.description = input.description;

    settings.updatedBy = actorId ? new Types.ObjectId(actorId) : undefined;
    await settings.save();

    await this.logAudit(sId, 'UPDATE_ACADEMIC_HOLIDAY', 'SchoolSettings', actorId, { holidayId, ...input });
    return settings;
  }

