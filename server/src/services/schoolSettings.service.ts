  /**
   * Get Academic Calendar view
   */
  public static async getAcademicCalendar(schoolId: Types.ObjectId | string): Promise<any> {
    const sId = new Types.ObjectId(schoolId);
    const settings = await this.getOrCreateSettings(sId);

    const [sessions, activeSession] = await Promise.all([
      AcademicSession.find({ schoolId: sId, isDeleted: false }).sort({ startDate: -1 }),
      AcademicSession.findOne({ schoolId: sId, isCurrent: true, isDeleted: false }),
    ]);

    return {
      activeSession,
      sessions,
      workingDays: settings.academic.workingDays,
      holidays: settings.academic.holidays,
      timezone: settings.regional.timezone,
    };
  }

  /**
   * Get or initialize Grading Scale
   */
  public static async getGradingPolicy(schoolId: Types.ObjectId | string): Promise<any> {
    const sId = new Types.ObjectId(schoolId);
    let scale = await GradingScale.findOne({ schoolId: sId, isDefault: true, isDeleted: false });

    if (!scale) {
      scale = await GradingScale.findOne({ schoolId: sId, isDeleted: false });
    }

    if (!scale) {
      // Create standard default grading scale
      scale = await GradingScale.create({
        schoolId: sId,
        name: 'Standard Institutional Scale',
        description: 'Default percentage-based letter grading with grade points',
        isDefault: true,
        bands: [
          { grade: 'A+', minPercentage: 90, maxPercentage: 100, gradePoint: 4.0, isPassing: true, description: 'Outstanding' },
          { grade: 'A', minPercentage: 80, maxPercentage: 89, gradePoint: 3.7, isPassing: true, description: 'Excellent' },
          { grade: 'B', minPercentage: 70, maxPercentage: 79, gradePoint: 3.0, isPassing: true, description: 'Good' },
          { grade: 'C', minPercentage: 60, maxPercentage: 69, gradePoint: 2.0, isPassing: true, description: 'Satisfactory' },
          { grade: 'D', minPercentage: 50, maxPercentage: 59, gradePoint: 1.0, isPassing: true, description: 'Pass' },
          { grade: 'F', minPercentage: 0, maxPercentage: 49, gradePoint: 0.0, isPassing: false, description: 'Fail' },
        ],
      });
    }

    return scale;
  }

  /**
   * Update Grading Policy & Validate Boundaries (Strictly prospective; never mutates published results)
   */
  public static async updateGradingPolicy(
    schoolId: Types.ObjectId | string,
    input: UpdateGradingScaleInput,
    actorId?: string,
    ip?: string,
    ua?: string
  ): Promise<any> {
    const sId = new Types.ObjectId(schoolId);

    // Validate boundaries: No overlapping bands, minPercentage <= maxPercentage
    const sortedBands = [...input.bands].sort((a, b) => b.minPercentage - a.minPercentage);

    for (let i = 0; i < sortedBands.length; i++) {
      const band = sortedBands[i];
      if (band.minPercentage > band.maxPercentage) {
        throw ApiError.badRequest(`Grade band "${band.grade}" has minPercentage greater than maxPercentage.`);
      }

      if (i > 0) {
        const higherBand = sortedBands[i - 1];
        if (band.maxPercentage >= higherBand.minPercentage) {
          throw ApiError.badRequest(
            `Overlapping grade boundaries detected between "${band.grade}" (${band.minPercentage}-${band.maxPercentage}) and "${higherBand.grade}" (${higherBand.minPercentage}-${higherBand.maxPercentage}).`
          );
        }
      }
    }

    let scale = await GradingScale.findOne({ schoolId: sId, isDefault: true, isDeleted: false });
    if (!scale) {
      scale = new GradingScale({
        schoolId: sId,
        isDefault: true,
      });
    }

    if (input.name) scale.name = input.name;
    if (input.description !== undefined) scale.description = input.description;
    scale.bands = sortedBands as IGradeBand[];

    await scale.save();

    await this.logAudit(
      sId,
      'UPDATE_GRADING_POLICY',
      'GradingScale',
      actorId,
      { scaleId: scale._id, bandsCount: scale.bands.length },
      ip,
      ua
    );

    return scale;
  }
